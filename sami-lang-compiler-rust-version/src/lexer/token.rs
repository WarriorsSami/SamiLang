#[derive(Debug, Eq, PartialEq, Hash)]
pub enum Token<'t> {
    Eof,
    // identifiers + literals
    Ident(&'t [u8]),
    Int(i32),
    // operators
    Assign,
    Plus,
    Minus,
    Bang,
    Asterisk,
    Slash,
    Lt,
    Gt,
    LtEq,
    GtEq,
    Eq,
    NotEq,
    // delimiters,
    Comma,
    Semicolon,
    LParen,
    RParen,
    LBrace,
    RBrace,
    // keywords,
    Function,
    Let,
    True,
    False,
    If,
    Else,
    Return,
}
